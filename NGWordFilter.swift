    private static var sortedByLengthDescending: [String] {
        prohibitedWords.sorted { $0.count > $1.count }
    }

    /// 該当した最初のNGワードを返す（無ければnil）。大文字小文字は区別しない
    static func firstProhibitedWord(in text: String) -> String? {
        let normalized = text.lowercased()
        return sortedByLengthDescending.first { normalized.contains($0.lowercased()) }
    }

    /// 本文中に含まれるNGワードを、その語と同じ文字数分の「＊」に置き換えて返す。
    /// 例：4文字のNGワードなら「＊＊＊＊」になる。該当が無ければ元のテキストをそのまま返す
    static func maskedText(_ text: String) -> String {
        var result = text
        for word in sortedByLengthDescending {
            guard !word.isEmpty else { continue }
            let mask = String(repeating: "＊", count: word.count)
            result = result.replacingOccurrences(of: word, with: mask, options: .caseInsensitive)
        }
        return result
    }
